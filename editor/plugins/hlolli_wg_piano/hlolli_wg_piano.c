static double wg_clamp(double value, double low, double high)
{
  if (!isfinite(value)) {
    return low;
  }
  if (value < low) {
    return low;
  }
  if (value > high) {
    return high;
  }
  return value;
}

static double wg_input(const MYFLT *value, double fallback)
{
  const double result = (double)*value;
  return isfinite(result) ? result : fallback;
}

